def build():
    themes = []
    for tid, tname, areas in THEMES:
        subs = []
        for area, strategies in areas:
            for st in strategies:
                subs.append(dict(id=st["id"], name=st["name"], hl_only=False, level=area, notes_url="",
                                 ref=st["ref"], cues=st["cues"], steps=st["steps"],
                                 formula=st["formula"] or None, trap=st["trap"] or None))
        themes.append(dict(id=tid, name=tname, notes_url="", subtopics=subs))
    ids = [x["id"] for t in themes for x in t["subtopics"]]
    assert len(ids) == len(set(ids)), "duplicate strategy id"
    return dict(subject="Maths AA SL", slug="maths-aa-sl",
                syllabus="IB DP Mathematics: analysis and approaches SL (first assessment 2021)",
                notes_site="", strategies=True, themes=themes)


def catalogue():
    """The list the labeller chooses from: id, name, area and cue phrases."""
    out = []
    for t in build()["themes"]:
        out.append(f"\n## {t['id']} {t['name']}")
        for x in t["subtopics"]:
            out.append(f"- {x['id']} {x['name']} ({x['level']}; {x['ref']}). Cues: " + "; ".join(x["cues"]))
    return "\n".join(out)


if __name__ == "__main__":
    out = ROOT / "bank/maths-aa-sl/syllabus.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    syl = build()
    out.write_text(json.dumps(syl, indent=1, ensure_ascii=False) + "\n")
    print(sum(len(t["subtopics"]) for t in syl["themes"]), "strategies →", out)
